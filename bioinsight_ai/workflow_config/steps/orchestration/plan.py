import uuid
from typing import List, Optional, Literal, Dict, Any
from pydantic import Field
from llama_index.core.workflow import Event
from xml.etree import ElementTree
from chainlit.element import Task, TaskList, TaskStatus
from typing import Dict, Any

class Action(Event):
    """
    Represents a single action in the orchestration plan.

    Compatibility note:
    LlamaIndex Context JsonSerializer expects component-like
    objects to expose a `class_name` attribute (or property) and to provide
    `to_dict()` and `from_dict()` methods. These exact names are relied on
    by the serializer's detection and reconstruction paths. Renaming or
    removing those members will break Context serialization/deserialization.
    """
    description: str
    agent_name: str
    status: Literal["ready", "running", "failed", "done"] = "ready"
    action_id: str = Field(default_factory=lambda: str(uuid.uuid4()))

    # JSON-serializer compatibility used by JsonSerializer in Context
    @property
    def class_name(self) -> str:
        """
        Qualified class name used by the JsonSerializer detection path.

        JsonSerializer checks for the presence of a `class_name` attribute on
        instances to decide whether to emit the `__is_component` envelope and
        call `to_dict()`/`from_dict()` during deserialization.

        This property returns the importable qualified name for the class.
        """
        return f"{self.__class__.__module__}.{self.__class__.__name__}"

    def to_dict(self) -> Dict[str, Any]:
        """
        Produce a JSON-serializable dict representing this Action.

        The dict must contain sufficient information
        for `Action.from_dict()` to reconstruct the instance.
        """
        return {
            "description": self.description,
            "agent_name": self.agent_name,
            "status": self.status,
            "action_id": self.action_id,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "Action":
        """
        Reconstruct an Action instance from a dictionary previously produced
        by `to_dict()`.

        This method intentionally tolerates missing keys by providing
        sensible defaults, but callers may want stricter validation in the
        future.
        """
        return cls(
            description=data.get("description", ""),
            agent_name=data.get("agent_name", ""),
            status=data.get("status", "ready"),
            action_id=data.get("action_id") or str(uuid.uuid4()),
        )

    def to_task(self) -> Task:
        """
        Convert the Action to a Chainlit Task.
        """
        return Task(
            title=self.description,
            status=TaskStatus(self.status),
            forId=self.action_id
        )

    def to_xml(self) -> str:
        """
        Convert the Action instance back into an XML string.
        """
        return f'<action agent="{self.agent_name}" action_id="{self.action_id}" {self.description}</action>'

class Plan(Event):
    """
    Represents a plan consisting of multiple actions.

    Compatibility note:
    LlamaIndex Context JsonSerializer expects component-like
    objects to expose a `class_name` attribute (or property) and to provide
    `to_dict()` and `from_dict()` methods. These exact names are relied on
    by the serializer's detection and reconstruction paths. Renaming or
    removing those members will break Context serialization/deserialization.
    """
    actions: List[Action] = []
    agent_names: List[str] = []  # List of valid agent names
    # Keep a reference to the Chainlit TaskList so we can update/remove it
    tasklist: Optional[TaskList] = None

    def __init__(self, xml_string: str, **data):
        super().__init__(**data)
        self.parse_xml(xml_string)

    def parse_xml(self, xml_string: str):
        """
        Parse the XML string and update or add actions.
        Ensure actions are added in the order they appear in the XML.
        Sanitizes unescaped special XML characters that may be generated by the LLM.
        """
        # Ensure the XML string contains <plan> tags
        plan_start = xml_string.find("<plan>")
        plan_end = xml_string.find("</plan>") + len("</plan>")
        if plan_start == -1 or plan_end == -1:
            raise ValueError("The XML string does not contain valid <plan> tags.")

        # Extract the <plan> block and store it as a string
        self.plan_xml = xml_string[plan_start:plan_end]

        # Sanitize the XML to handle unescaped special characters in action text
        # This is necessary because LLMs may generate descriptions with < and > characters
        # that are not valid XML (e.g., "ranges: <40, 40-49" should have < escaped as &lt;)
        sanitized_xml = self._sanitize_xml(self.plan_xml)

        try:
            root = ElementTree.fromstring(sanitized_xml)
        except ElementTree.ParseError as e:
            raise ValueError(f"Invalid XML format within <plan> tags: {e}")

        self.actions = []  # Clear existing actions to ensure correct order

        for action_elem in root.findall("action"):
            action_id = action_elem.get("action_id")
            agent_name = action_elem.get("agent")
            description = action_elem.text.strip() if action_elem.text else ""

            # Validate required fields
            if not action_id:
                raise ValueError("Each <action> must have a unique 'action_id' attribute.")

            if not agent_name:
                raise ValueError(f"Action '{action_id}' is missing the required 'agent' attribute.")

            if agent_name not in self.agent_names:
                raise ValueError(f"Agent '{agent_name}' is not a valid agent. Valid agents are: {', '.join(self.agent_names)}.")

            # Create a new action and maintain the order
            new_action = Action(
                description=description,
                agent_name=agent_name,
                action_id=action_id,
            )
            self.actions.append(new_action)

    def _sanitize_xml(self, xml_string: str) -> str:
        """
        Sanitize XML to handle unescaped special characters that LLMs may generate.

        Specifically handles:
        - Unescaped < and > characters in text content that should be &lt; and &gt;
        - Preserves properly formatted tags and attributes

        This regex-based approach:
        1. Matches text content between > and < (i.e., between XML tags)
        2. Escapes any < or > that aren't part of valid XML entities or tags
        """
        import re

        # Strategy: Find all text content between tags and escape unescaped < and > characters
        # We use a more careful approach: split on actual tags, process text, rejoin

        # Pattern to find all tags (including closing tags, self-closing, and comments)
        tag_pattern = r'(<[^>]+>)'
        parts = re.split(tag_pattern, xml_string)

        result = []
        for i, part in enumerate(parts):
            if i % 2 == 0:
                # This is text content (not a tag)
                # Escape unescaped < and > characters
                # But preserve existing XML entities like &lt; &gt; &amp; &quot; &apos;

                # First, temporarily replace existing entities so we don't double-escape them
                part = part.replace('&lt;', '\x00LT\x00')
                part = part.replace('&gt;', '\x00GT\x00')
                part = part.replace('&amp;', '\x00AMP\x00')
                part = part.replace('&quot;', '\x00QUOT\x00')
                part = part.replace('&apos;', '\x00APOS\x00')

                # Now escape any remaining unescaped < and >
                part = part.replace('<', '&lt;')
                part = part.replace('>', '&gt;')

                # Restore the original entities
                part = part.replace('\x00LT\x00', '&lt;')
                part = part.replace('\x00GT\x00', '&gt;')
                part = part.replace('\x00AMP\x00', '&amp;')
                part = part.replace('\x00QUOT\x00', '&quot;')
                part = part.replace('\x00APOS\x00', '&apos;')

            result.append(part)

        return ''.join(result)

    # JSON-serializer compatibility used by JsonSerializer in Context
    @property
    def class_name(self) -> str:
        """
        Qualified class name used by the JsonSerializer detection path.

        The presence of a `class_name` attribute on an instance signals to
        JsonSerializer that it should package the result of `to_dict()` in
        a component envelope and call `Plan.from_dict()` on deserialization.
        """
        return f"{self.__class__.__module__}.{self.__class__.__name__}"

    def to_dict(self) -> Dict[str, Any]:
        """
        Produce a JSON-serializable dict representing this Plan.
        """
        return {
                # store the original XML string used to construct the Plan so
                # it can be reparsed on deserialization if needed
                "plan_xml": getattr(self, "plan_xml", None),
                "actions": [a.to_dict() for a in self.actions],
                "agent_names": list(self.agent_names),
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "Plan":
        """
        Reconstruct a Plan from a dict produced by `to_dict()`.

        Behavior and precedence:
        1. We attempt to reparse `plan_xml` (if present) to reconstruct the
           original plan structure and order.
        2. If the serialized payload contains an `actions` list, those action
           entries are considered authoritative and will overwrite the
           actions resulting from the parsed XML. This lets action updates
           survive serialization.

        Note: The class expects the module path to remain importable so the
        serializer can resolve `Plan` via its qualified name.
        """
        plan_xml = data.get("plan_xml", "<plan></plan>")

        # Restore agent names first so parse_xml can validate agent membership
        agent_names = data.get("agent_names", [])

        # Create a lightweight Plan instance without parsing the real xml yet.
        # We instantiate with an empty plan to avoid parse-time validation
        # against an empty `agent_names` list.
        plan = cls("<plan></plan>")
        plan.agent_names = agent_names

        # Now reparse the actual XML (this will validate against restored
        # agent names).
        plan.parse_xml(plan_xml)

        # If actions are provided in the dict, they represent the authoritative
        # state (they may have been updated since the original XML was parsed),
        # so use them. Otherwise keep the actions parsed from the XML.
        if "actions" in data and data.get("actions") is not None:
            plan.actions = [Action.from_dict(a) for a in data.get("actions", [])]

        # Ensure the stored plan_xml is kept on the instance for future
        # serializations.
        plan.plan_xml = plan_xml

        return plan

    def current_action(self) -> Optional[Action]:
        """
        Get the current action. If the current action is "done",
        move to the next action with a status of "ready".
        """
        running_action = next((a for a in self.actions if a.status == "running"), None)
        if running_action:
            return running_action

        # Find the next action with a status of "ready" after the last "done" action
        last_done_index = next((i for i, a in reversed(list(enumerate(self.actions))) if a.status == "done"), -1)
        for action in self.actions[last_done_index + 1:]:
            if action.status == "ready":
                return action

        # Default to the first "ready" action if no "done" actions exist
        return next((a for a in self.actions if a.status == "ready"), None)

    def previous_action(self) -> Optional[Action]:
        """
        Get the previous action.
        """
        current = self.current_action()
        if current:
            current_index = self.actions.index(current)
            if current_index > 0:
                return self.actions[current_index - 1]
        return None

    def next_action(self) -> Optional[Action]:
        """
        Get the next action with a status of "ready" in the correct order.
        """
        for action in self.actions:
            if action.status == "ready":
                return action
        return None

    def to_tasklist(self) -> TaskList:
        """
        Convert the Plan to a Chainlit TaskList, store it on the Plan
        for future updates/removal, and return it.
        """
        if self.tasklist is None:
            self.tasklist = TaskList()

        # Populate the stored tasklist
        self.tasklist.tasks = [action.to_task() for action in self.actions]
        self.tasklist.status = self.tasklist_status()
        return self.tasklist

    async def update_tasklist(self, tasklist: Optional[TaskList] = None):
        """
        Update the Chainlit TaskList dynamically.

        Backwards compatible: callers may pass a TaskList instance. If no
        TaskList is passed, the Plan's stored TaskList will be used (and
        created if necessary).
        """
        target = tasklist or self.tasklist
        if target is None:
            # Lazily create and store a TaskList if none exists
            target = self.to_tasklist()

        target.tasks = [action.to_task() for action in self.actions]
        target.status = self.tasklist_status()
        await target.update()

    async def remove_tasklist(self):
        """
        Remove the stored TaskList from the Chainlit UI.

        This calls TaskList.remove() (async) and clears the stored reference.
        If no TaskList is stored, this is a no-op.
        """
        if self.tasklist is None:
            return

        # TaskList.remove() is async in Chainlit
        await self.tasklist.remove()
        self.tasklist = None

    def __str__(self):
        """
        Return a dynamically generated XML representation of the current Plan object.
        This ensures the string representation reflects the current state of the actions.
        """
        actions_xml = "\n".join(
            f'<action agent="{action.agent_name}" action_id="{action.action_id}" status="{action.status}">{action.description}</action>'
            for action in self.actions
        )
        return f'<plan>\n{actions_xml}\n</plan>'

    def __iter__(self):
        """
        Make the Plan object iterable over its actions.
        """
        return iter(self.actions)

    def tasklist_status(self) -> str:
        """
        Calculate the overall status of the TaskList based on the actions' statuses.
        """
        if all(action.status == "done" for action in self.actions):
            return "Completed"
        elif any(action.status == "running" for action in self.actions):
            return "In Progress"
        elif all(action.status == "ready" for action in self.actions):
            return "Ready"
        elif any(action.status == "failed" for action in self.actions):
            return "Failed"
        else:
            return "Partially Completed"
