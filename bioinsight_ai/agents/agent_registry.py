import json
from typing import List, Union
from pydantic import BaseModel, field_validator
from .bioinsight_agent import BioInsightAgent
from .bioinsight_agent_workflow import BioInsightAgentWorkflow

class AgentRegistry(BaseModel):
    agents: List[Union[BioInsightAgent, BioInsightAgentWorkflow]]
    agent_schema: list = []
    agent_schema_str: str = ""

    model_config = {
        "arbitrary_types_allowed": True
    }

    @field_validator("agents")
    @classmethod
    def check_unique_names(cls, agents: List[Union[BioInsightAgent, BioInsightAgentWorkflow]]) -> List[Union[BioInsightAgent, BioInsightAgentWorkflow]]:
        """
        Validate that all agent names in the registry are unique.

        Args:
            agents (List[Union[BioInsightAgent, BioInsightAgentWorkflow]]): List of agents to validate.

        Returns:
            List[Union[BioInsightAgent, BioInsightAgentWorkflow]]: The validated list of agents.

        Raises:
            ValueError: If duplicate agent names are found.
        """
        names = [agent.name for agent in agents]
        duplicates = {name for name in names if names.count(name) > 1}
        if duplicates:
            raise ValueError(f"Duplicate agent names found in the registry: {', '.join(duplicates)}")
        return agents

    def __init__(self, **data) -> None:
        super().__init__(**data)
        # Create a dictionary mapping agent names to agents
        self._agent_dict = {agent.name: agent for agent in self.agents}
        # Initialize schemas
        self.gather_agent_schemas()

    def __getitem__(self, agent_name: str) -> Union[BioInsightAgent, BioInsightAgentWorkflow]:
        """
        Allow dictionary-like access to agents by their names.

        Args:
            agent_name (str): The name of the agent to retrieve.

        Returns:
            Union[BioInsightAgent, BioInsightAgentWorkflow]: The agent with the specified name.

        Raises:
            KeyError: If the agent name does not exist in the registry.
        """
        return self._agent_dict[agent_name]

    def get(self, agent_name: str, default: None = None) -> Union[BioInsightAgent, BioInsightAgentWorkflow, None]:
        """
        Retrieve an agent by name with a default value if the name does not exist.

        Args:
            agent_name (str): The name of the agent to retrieve.
            default: The value to return if the agent name does not exist. Defaults to None.

        Returns:
            Union[BioInsightAgent, BioInsightAgentWorkflow, Any]: The agent with the specified name or the default value.
        """
        return self._agent_dict.get(agent_name, default)

    def add_agent(self, agent: Union[BioInsightAgent, BioInsightAgentWorkflow]) -> None:
        """
        Add a new agent to the registry, validate, and reinitialize the model.

        Args:
            agent (Union[BioInsightAgent, BioInsightAgentWorkflow]): The agent to add.

        Raises:
            ValueError: If the new agent causes validation to fail.
        """
        # Append the new agent to the agents list
        updated_agents = self.agents + [agent]

        # Validate the updated agents list
        validated_data = self.__class__(agents=updated_agents)

        # Reinitialize the current instance with the validated data
        self.__dict__.update(validated_data.__dict__)

        # Update schemas
        self.gather_agent_schemas()

    def remove_agent(self, agent_name: str) -> Union[BioInsightAgent, BioInsightAgentWorkflow]:
        """
        Remove an agent from the registry by name, re-validate the model, and update schemas.

        Returns the removed agent instance.

        Raises:
            KeyError: if the agent name does not exist in the registry.
        """
        if agent_name not in self._agent_dict:
            raise KeyError(f"Agent '{agent_name}' not found in registry.")

        # Pop from internal dict and rebuild agents list
        removed_agent = self._agent_dict.pop(agent_name)

        # Rebuild the agents list without the removed agent
        self.agents = [a for a in self.agents if a.name != agent_name]

        # Re-validate / reinitialize model state (same approach as add_agent)
        validated_data = self.__class__(agents=self.agents)
        self.__dict__.update(validated_data.__dict__)

        # Update schemas
        self.gather_agent_schemas()

        return removed_agent

    def gather_agent_schemas(self) -> None:
        """
        Gather the schemas generated by all agents in the registry and update attributes.

        Updates:
            - self.agent_schema: List of dictionaries representing the schemas of all agents.
            - self.agent_schema_str: JSON string representation of the schemas.
        """
        self.agent_schema = [agent.generate_schema() for agent in self.agents]
        self.agent_schema_str = json.dumps(self.agent_schema, indent=2)

    def names(self) -> list[str]:
        """
        Retrieve the names of all agents in the registry.

        Returns:
            list[str]: A list of agent names.
        """
        return list(self._agent_dict.keys())
